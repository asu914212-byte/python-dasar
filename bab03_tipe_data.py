# Bab 3: Tipe Data Dasar Python

# Tipe data String
nama = "Dandy"

# Tipe data Integer
umur = 17

# Tipe data Float
tinggi = 170.5

# Tipe data Boolean
pelajar = True

# Menampilkan nilai dan tipe datanya
print("Nama:", nama, "| Tipe:", type(nama))
print("Umur:", umur, "| Tipe:", type(umur))
print("Tinggi:", tinggi, "| Tipe:", type(tinggi))
print("Pelajar:", pelajar, "| Tipe:", type(pelajar))