# Bab 9: Daftar, Tuple, dan Himpunan

# List (Daftar)
buah = ["Apel", "Jeruk", "Mangga"]
buah.append("Pisang")

print("Daftar Buah:", buah)
print("Buah pertama:", buah[0])

# Tuple
warna = ("Merah", "Biru", "Hijau")

print("Daftar Warna:", warna)
print("Warna pertama:", warna[0])

# Set (Himpunan)
angka = {1, 2, 3, 4, 4, 5}

print("Himpunan Angka:", angka)
angka.add(6)

print("Setelah ditambah:", angka)