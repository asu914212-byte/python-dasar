# Bab 4: Variabel dalam Python

# Membuat variabel
nama = "Dandy Fahri"
kelas = "XI RPL B"
umur = 17
hobi = "Menggambar"

# Mengubah nilai variabel
umur = 18

# Menampilkan isi variabel
print("Nama:", nama)
print("Kelas:", kelas)
print("Umur:", umur)
print("Hobi:", hobi)

# Menggabungkan variabel
print("\nPerkenalkan, nama saya", nama)
print("Saya dari kelas", kelas)